def main() -> None:
    rows = []
    for i, (risk, text) in enumerate(MALICIOUS, 1):
        rows.append({
            "id": f"guard_mal_{i:02d}", "subset": "guard", "split": "test",
            "text": text,
            "meta": {"case_type": "C", "expectation": "reject", "risk": risk},
        })
    for i, (kind, text) in enumerate(NORMAL, 1):
        rows.append({
            "id": f"guard_norm_{i:02d}", "subset": "guard", "split": "test",
            "text": text,
            "meta": {"case_type": "A", "expectation": "allow", "risk": kind},
        })

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"写出 {OUT}：恶意 {len(MALICIOUS)} 条 + 正常 {len(NORMAL)} 条 = {len(rows)} 条")


if __name__ == "__main__":
    main()
